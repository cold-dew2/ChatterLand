"""발음 추가 콘텐츠: 음절 따라 말하기(자음·모음·받침)와 비슷한 소리 구별(최소 대립 낱말).
음절 연습은 언어치료에서 쓰는 '자음 + 모음' 조합 연습이며, 조합 규칙으로 만든다(무작위 문자열 아님).
비슷한 소리 구별 낱말은 직접 작성했다. build_seed.py가 목표 자모 포함 여부를 다시 검증한다. 뒤에만 추가한다."""

ONSETS = "ㄱ ㄲ ㄴ ㄷ ㄸ ㄹ ㅁ ㅂ ㅃ ㅅ ㅆ ㅇ ㅈ ㅉ ㅊ ㅋ ㅌ ㅍ ㅎ".split()
NUCLEI = "ㅏ ㅐ ㅑ ㅒ ㅓ ㅔ ㅕ ㅖ ㅗ ㅘ ㅙ ㅚ ㅛ ㅜ ㅝ ㅞ ㅟ ㅠ ㅡ ㅢ ㅣ".split()
CODAS = [""] + "ㄱ ㄲ ㄳ ㄴ ㄵ ㄶ ㄷ ㄹ ㄺ ㄻ ㄼ ㄽ ㄾ ㄿ ㅀ ㅁ ㅂ ㅄ ㅅ ㅆ ㅇ ㅈ ㅊ ㅋ ㅌ ㅍ ㅎ".split()


def compose(onset, nucleus, coda=""):
    return chr(0xAC00 + (ONSETS.index(onset) * 21 + NUCLEI.index(nucleus)) * 28 + CODAS.index(coda))


# 자음(ㅇ 제외 18개)별 음절 세트: (세트 이름, 모음 묶음, 받침)
CONSONANTS = [c for c in ONSETS if c != 'ㅇ']
SYLLABLE_GROUPS = [
    ('기본 모음 음절', "ㅏ ㅓ ㅗ ㅜ ㅡ".split(), ""),
    ('ㅣ 모음 음절', "ㅣ ㅐ ㅔ ㅚ ㅟ".split(), ""),
    ('이중 모음 음절', "ㅑ ㅕ ㅛ ㅠ ㅘ".split(), ""),
    ('받침 음절', ["ㅏ"] * 5, "ㄱ ㄴ ㄹ ㅁ ㅇ".split()),
]


def consonant_syllable_sets():
    """[(목표 자음, 세트 이름, [음절 5개])]"""
    out = []
    for name, vowels, codas in SYLLABLE_GROUPS:
        for c in CONSONANTS:
            if codas:
                items = [compose(c, v, k) for v, k in zip(vowels, codas)]
            else:
                items = [compose(c, v) for v in vowels]
            out.append((c, name, items))
    return out


# 모음별 음절 세트: 같은 모음을 여러 자음과 함께 말한다.
VOWEL_ONSETS = "ㅇ ㄱ ㄴ ㅁ ㅂ".split()
VOWELS_FOR_DRILL = "ㅏ ㅓ ㅗ ㅜ ㅡ ㅣ ㅐ ㅔ ㅑ ㅕ ㅛ ㅠ ㅘ ㅝ ㅚ ㅟ".split()


def vowel_syllable_sets():
    return [(v, '모음 음절', [compose(o, v) for o in VOWEL_ONSETS]) for v in VOWELS_FOR_DRILL]


